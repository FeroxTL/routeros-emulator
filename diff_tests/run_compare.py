"""Differential harness: RouterOS emulator vs a real device.

Usage:
    python3 run_compare.py [probe1.rsc ...]   # default: all probes/*.rsc

For each probe the file is run as a whole script:
  - on the emulator (routeros.launcher)      -> the :put output in interp.output
  - on the device  (ssh / sshpass)           -> the :put output of the device
Then a per-line diff is printed.
"""

import argparse
import os
import subprocess
import sys
from pathlib import Path

HOST = os.environ.get("MIKROTIK_HOST", "192.168.88.1")
USER = os.environ.get("MIKROTIK_USER", "admin")
PASS = os.environ.get("MIKROTIK_PASS", "")

HERE = Path(__file__).resolve().parent
PROBES = HERE / "probes"
ROOT = HERE.parent  # repo root containing the `routeros` package
sys.path.insert(0, str(ROOT))

# ruff: noqa: E402
from routeros.device_model import DeviceModel  # noqa: E402
from routeros.launcher import load_source  # noqa: E402


def run_emulator(source: str):
    """Run ``source`` as a whole on the emulator, return the list of output lines."""
    try:
        script = load_source(source, DeviceModel(), run_main=True)
        return script.interp.output, None
    except Exception as exc:  # noqa: BLE001
        return None, f"{type(exc).__name__}: {exc}"


def run_device(source: str):
    """Run ``source`` as a whole on the device over SSH, return the output lines."""
    env = dict(os.environ)
    env["SSHPASS"] = PASS
    try:
        p = subprocess.run(
            [
                "sshpass", "-e", "ssh",
                "-o", "StrictHostKeyChecking=no",
                "-o", "UserKnownHostsFile=/dev/null",
                "-o", "ConnectTimeout=6",
                f"{USER}@{HOST}",
                source,
            ],
            env=env, capture_output=True, text=True, timeout=30,
        )
    except Exception as exc:  # noqa: BLE001
        return None, f"ssh: {type(exc).__name__}: {exc}"
    if p.returncode != 0:
        return None, f"ssh rc={p.returncode}: {p.stderr.strip()}"
    return p.stdout.splitlines(), None


def strip_cr(lines):
    return [ln.rstrip("\r") for ln in lines]


def _marker(i: int) -> str:
    return f"ERR:{i}"


def _build_batch(lines):
    """Wrap each probe so it prints exactly one line and a failure does not abort
    the rest: `:do { <probe> } on-error={ :put "ERR:n" }`. Lines that are not
    syntactically valid cannot be wrapped this way, so they are kept separate.
    """
    out = []
    for i, ln in enumerate(lines, start=1):
        out.append(f':do {{ {ln} }} on-error={{ :put "{_marker(i)}" }}')
    return "\n".join(out)


def compare_source(path: Path):
    source = path.read_text(encoding="utf-8")
    # Real probes: non-empty lines, not comments, not the "# N =" captions. The
    # captions are regenerated by hand — only code lines are kept.
    raw_lines = [ln for ln in source.splitlines()]
    lines = []
    stdouts = []  # (stdout, stderr) from devices, for diagnostics
    for ln in raw_lines:
        s = ln.strip()
        if not s or s.startswith("#"):
            continue
        lines.append(s)

    print(f"\n===== {path.name}  ({len(lines)} probes) =====")

    CHUNK = 10
    global_no = 0
    mism = 0
    for start in range(0, len(lines), CHUNK):
        chunk = lines[start : start + CHUNK]
        chunk_results = _compare_chunk(lines, chunk, start)
        if chunk_results is None:
            for j, ln in enumerate(chunk):
                global_no += 1
                print(f"  [?  ] {global_no:>3} | {ln}")
            continue
        for j, (ln, e, d, err) in enumerate(chunk_results):
            global_no += 1
            same = (e == d) and not err
            mark = "OK  " if same else "DIFF"
            if same:
                print(f"  [{mark}] {global_no:>3} | {ln}")
            else:
                mism += 1
                print(f"  [{mark}] {global_no:>3} | {ln}")
                print(f"        emulator : {e!r}")
                print(f"        device   : {d!r}")
    print(f"  --- mismatches: {mism}/{len(lines)} ---")


def _compare_chunk(all_lines, chunk, start):
    """The device runs a whole chunk as one batch (a single SSH session, with
    every line wrapped in :do/on-error so one failing line does not break the
    rest). The emulator runs line by line (in memory) so a local parse failure
    of one line does not take down the whole emulator batch."""
    batch = _build_batch(chunk)
    dev, d_err = run_device(batch)
    if d_err:
        print(f"        [device on chunk {start + 1}..{start + len(chunk)}: {d_err}]")
        return None
    dev = [l.rstrip("\r") for l in (dev or [])]

    res = []
    for k, ln in enumerate(chunk):
        d = dev[k] if k < len(dev) else "<missing>"
        err_flag = (d == f"ERR:{start + k + 1}")
        if err_flag:
            d = "<device error>"
        e, e_err = run_emulator(ln)
        if e_err:
            e = f"<parse/error: {e_err}>"
        else:
            e = " | ".join(e) if e else ""
        res.append((ln, e, d, err_flag))
    return res


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("files", nargs="*", help="specific .rsc files")
    args = ap.parse_args()
    if args.files:
        files = []
        for f in args.files:
            p = Path(f)
            if not p.exists():
                p2 = PROBES / (f if f.endswith(".rsc") else f"{f}.rsc")
                p = p2
            files.append(p.absolute())
    else:
        files = sorted(PROBES.glob("*.rsc"))
    for f in files:
        if f.suffix != ".rsc":
            f = f.with_suffix(".rsc")
        compare_source(f)


if __name__ == "__main__":
    main()